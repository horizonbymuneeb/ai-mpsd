$ResourceGroup = 'rg-portal-demo-13'
$Location = 'eastus'
$TemplateFile = 'C:\Scripts\templates\portal-demo.json'
$ParameterFile = 'C:\Scripts\templates\portal-demo.parameters.json'
$SubscriptionId = '092721ec-5269-d10d-bfd5-65a148162c3f'
$StorageAccount = 'stdemo2930'
$VmName = 'vm-portal-demo-13'
