
$WarningDays = 60
$Hosts       = @('portal.contoso.com', 'api.contoso.com', 'vpn.contoso.com')
$Port        = 9443
$ReportPath  = 'C:\Reports\cert-expiry-2026-05-16.csv'

$WarningPreference = 'Continue'
